import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'msedge',headless:true})
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:5173',{waitUntil:'networkidle'})
 await page.getByRole('button',{name:'Vista previa',exact:true}).click()
 await page.getByRole('heading',{name:'Resumen general'}).waitFor()
 assert.equal(await page.getByRole('option',{name:'Inventario',exact:true}).count(),0)
 assert.equal(await page.getByRole('button',{name:'Notificaciones',exact:true}).count(),0)
 const sections=['Pacientes','Historias clínicas','Personal','Tratamientos','Planes de tratamiento','Presupuestos','Pagos y comprobantes','Estados de cuenta','Cuentas por cobrar','Usuarios','Roles y permisos']
 const nav=page.getByRole('navigation')
 for(const name of sections){
  await nav.getByRole('button',{name,exact:true}).click()
  await page.getByRole('heading',{name:'Sin registros disponibles',exact:true}).waitFor()
  assert.equal(await page.locator('tbody tr').count(),0)
 }
 for(const name of ['Citas','Agenda','Inventario','Odontograma','Atenciones','Compras','Proveedores','Consultorios'])assert.equal(await nav.getByRole('button',{name,exact:true}).count(),0)
 await page.getByRole('button',{name:'Perfil',exact:true}).click()
 await page.locator('.d-popover.profile strong').filter({hasText:'Administrador'}).waitFor()
 await page.getByRole('button',{name:'Perfil',exact:true}).click()
 await page.getByRole('navigation').getByRole('button',{name:'Pacientes',exact:true}).click()
 await page.getByRole('textbox',{name:'Buscar registros'}).fill('consulta')
 assert.equal(await page.locator('tbody tr').count(),0)
 await page.getByRole('textbox',{name:'Buscar registros'}).fill('')
 await page.getByRole('button',{name:'Nuevo paciente',exact:true}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByLabel('Tipo de documento *',{exact:true}).fill('DNI')
 await dialog.getByLabel('Documento *',{exact:true}).fill('99019999')
 await dialog.getByLabel('Nombres *',{exact:true}).fill('Paciente')
 await dialog.getByLabel('Apellidos *',{exact:true}).fill('De prueba')
 await dialog.getByLabel('Teléfono *',{exact:true}).fill('900999999')
 await dialog.getByRole('button',{name:'Validar datos',exact:true}).click()
 await page.getByRole('status').filter({hasText:'Validación completada'}).waitFor()
 assert.equal(await page.locator('tbody tr').count(),0)
 await page.getByLabel('Perfil de vista previa').selectOption('PACIENTE')
 assert.equal(await page.getByRole('button',{name:'Usuarios',exact:true}).count(),0)
 await page.getByRole('button',{name:'Mi estado de cuenta',exact:true}).click()
 await page.waitForTimeout(100)
 assert.equal(await page.locator('tbody tr').count(),0)
 await page.setViewportSize({width:390,height:844})
 await page.waitForTimeout(350)
 const closed=await page.locator('.d-sidebar').boundingBox();assert.ok(closed&&closed.x+closed.width<=1,'La navegación móvil debe iniciar cerrada')
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'La página no debe desbordarse en móvil')
 const toast=page.getByRole('button',{name:'Cerrar aviso',exact:true});if(await toast.count())await toast.click()
 await page.getByRole('button',{name:'Abrir navegación',exact:true}).click()
 await page.getByRole('button',{name:'Cerrar navegación',exact:true}).click()
 await page.waitForTimeout(350)
 await page.setViewportSize({width:1440,height:1000})
 await page.getByRole('button',{name:'Salir de la vista previa',exact:true}).click()
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
 await page.getByLabel('Correo o usuario').fill('prueba@example.invalid')
 await page.getByLabel('Contraseña',{exact:true}).fill('clave-ficticia-de-prueba')
 await page.getByRole('button',{name:'Mostrar contraseña',exact:true}).click()
 assert.equal(await page.getByLabel('Contraseña',{exact:true}).getAttribute('type'),'text')
 await page.getByRole('button',{name:'Ingresar al sistema',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'No fue posible iniciar sesión'}).waitFor()
 assert.equal(errors.length,0,errors.join('\n'))
 console.log('OK UI: 11 vistas vacías del alcance, sin datos ficticios ni módulos aplazados; formularios, perfil, actor paciente, móvil y login.')
}finally{await browser.close()}
